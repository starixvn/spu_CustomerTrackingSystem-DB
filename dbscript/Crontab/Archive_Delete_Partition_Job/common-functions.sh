logger_init(){
    [[ -d $LOG_PATH ]] || mkdir -p $LOG_PATH
}

do_log(){
  mkdir -p $LOG_PATH
  SEVERITY=$1
  shift
  printf "$LOG_MESSAGEFORMAT" "$(date +"$LOG_DATEFORMAT")" "$SEVERITY" "$*" >> $LOG_PATH/$LOG_FILE
  [[ $LOG_STDOUT ]] && printf "$LOG_MESSAGEFORMAT" "$(date +"$LOG_DATEFORMAT")" "$SEVERITY" "$*"
}