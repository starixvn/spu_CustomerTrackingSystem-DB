#! /bin/bash



function copy_archive_partition(){
    DB_NAME=$1
    TABLE_NAME=$2
    
    SLAVE_DB_HOST=$3
    SLAVE_DB_PORT=$4
    SLAVE_DB_USER=$5
    SLAVE_DB_PASS=$6
    SLAVE_PARTITION_FILE_NAME=$7
    SLAVE_PARTITION_CFG_FILE_NAME=$8
    SLAVE_MACHINE_TEMP_FOLDER=$9

    SLAVE_CONTAINER_NAME=${10}
    SLAVE_CONTAINER_DATA_PATH=${11}

    ARCHIVE_MACHINE_HOST=${12}
    ARCHIVE_MACHINE_USER=${13}
    ARCHIVE_MACHINE_PASS=${14}
    ARCHIVE_MACHINE_TEMP_FOLDER=${15} 

   
    SLAVE_PARTITION_FILE_PATH="${SLAVE_CONTAINER_DATA_PATH}${SLAVE_PARTITION_FILE_NAME}"
    ARCHIVE_MACHINE_TEMP_PARTITION_FILE="${TABLE_NAME}_Archive_Temp.ibd"
    ARCHIVE_MACHINE_TEMP_PARTITION_FILE_PATH="${ARCHIVE_MACHINE_TEMP_FOLDER}${ARCHIVE_MACHINE_TEMP_PARTITION_FILE}"
    
    SLAVE_PARTITION_CFG_FILE_PATH="${SLAVE_CONTAINER_DATA_PATH}${SLAVE_PARTITION_CFG_FILE_NAME}"
    ARCHIVE_MACHINE_TEMP_PARTITION_CFG_FILE="${TABLE_NAME}_Archive_Temp.cfg"
    ARCHIVE_MACHINE_TEMP_PARTITION_CFG_FILE_PATH="${ARCHIVE_MACHINE_TEMP_FOLDER}${ARCHIVE_MACHINE_TEMP_PARTITION_CFG_FILE}"


    log_info "copy_archive_partition >> copy partition"
    mkdir -p $SLAVE_MACHINE_TEMP_FOLDER
    SLAVE_PARTITION_FILE_PATH="${SLAVE_PARTITION_FILE_PATH//"#"/"'#'"}"
    SLAVE_PARTITION_CFG_FILE_PATH="${SLAVE_PARTITION_CFG_FILE_PATH//"#"/"'#'"}"

    
    log_info "copy_archive_partition >> FLUSH TABLES $TABLE_NAME copy partition"
    log_info "copy_archive_partition >> copy partition in container to temp folder"
    MYSQL_QUERY="USE $DB_NAME; FLUSH TABLES $TABLE_NAME FOR EXPORT; system docker cp $SLAVE_CONTAINER_NAME:$SLAVE_PARTITION_FILE_PATH $SLAVE_MACHINE_TEMP_FOLDER;system  docker cp $SLAVE_CONTAINER_NAME:$SLAVE_PARTITION_CFG_FILE_PATH $SLAVE_MACHINE_TEMP_FOLDER;"
    mysql --user="$SLAVE_DB_USER" --password="$SLAVE_DB_PASS" --host="$SLAVE_DB_HOST" --port=$SLAVE_DB_PORT  -e "$MYSQL_QUERY"

    log_info "copy_archive_partition >> UNLOCK TABLE $DB_NAME.$TABLE_NAME"
    MYSQL_QUERY="UNLOCK TABLES;"
    mysql --user="$SLAVE_DB_USER" --password="$SLAVE_DB_PASS" --host="$SLAVE_DB_HOST" --port=$SLAVE_DB_PORT -e "$MYSQL_QUERY"
    

    SLAVE_PARTITION_FILE_PATH="${SLAVE_MACHINE_TEMP_FOLDER}${SLAVE_PARTITION_FILE_NAME}"
    SLAVE_PARTITION_CFG_FILE_PATH="${SLAVE_MACHINE_TEMP_FOLDER}${SLAVE_PARTITION_CFG_FILE_NAME}"

    log_info "copy_archive_partition >> copy partition in temp folder to archive machine folder"
    sshpass -p "$ARCHIVE_MACHINE_PASS" ssh -o StrictHostKeyChecking=no $ARCHIVE_MACHINE_USER@$ARCHIVE_MACHINE_HOST mkdir -p $ARCHIVE_MACHINE_TEMP_FOLDER
    sshpass -p "$ARCHIVE_MACHINE_PASS" scp $SLAVE_PARTITION_FILE_PATH  $ARCHIVE_MACHINE_USER@$ARCHIVE_MACHINE_HOST:$ARCHIVE_MACHINE_TEMP_PARTITION_FILE_PATH
    sshpass -p "$ARCHIVE_MACHINE_PASS" scp $SLAVE_PARTITION_CFG_FILE_PATH  $ARCHIVE_MACHINE_USER@$ARCHIVE_MACHINE_HOST:$ARCHIVE_MACHINE_TEMP_PARTITION_CFG_FILE_PATH
    
    


}

function import_partition_table(){
    ARCHIVE_DB_NAME=$1
    ARCHIVE_TABLE_NAME=$2

    ARCHIVE_DB_HOST=$3
    ARCHIVE_DB_PORT=$4
    ARCHIVE_DB_USER=$5
    ARCHIVE_DB_PASS=$6
    

    ARCHIVE_MACHINE_HOST=$7
    ARCHIVE_MACHINE_USER=$8
    ARCHIVE_MACHINE_PASS=$9
    ARCHIVE_MACHINE_TEMP_FOLDER=${10}

    ARCHIVE_CONTAINER_NAME=${11}
    ARCHIVE_CONTAINER_DATA_PATH=${12} 

    ARCHIVE_NEW_PARTITION_NAME=${13}
    ARCHIVE_NEW_PARTITION_DESCRIPTION=${14}
    ARCHIVE_NEW_PARTITION_MAXVALUE=${15}
    


    log_info "Prepare a temporary table to import the tablespace: $ARCHIVE_DB_NAME.$ARCHIVE_TABLE_NAME"
    MYSQL_QUERY="CREATE TABLE $ARCHIVE_DB_NAME.${ARCHIVE_TABLE_NAME}_Archive_Temp LIKE $ARCHIVE_DB_NAME.$ARCHIVE_TABLE_NAME;"
    mysql --user="$ARCHIVE_DB_USER" --password="$ARCHIVE_DB_PASS" --host="$ARCHIVE_DB_HOST" --port=$ARCHIVE_DB_PORT -e "$MYSQL_QUERY"

    MYSQL_QUERY="ALTER TABLE $ARCHIVE_DB_NAME.${ARCHIVE_TABLE_NAME}_Archive_Temp REMOVE PARTITIONING;"
    mysql --user="$ARCHIVE_DB_USER" --password="$ARCHIVE_DB_PASS" --host="$ARCHIVE_DB_HOST" --port=$ARCHIVE_DB_PORT -e "$MYSQL_QUERY"
    
    MYSQL_QUERY="ALTER TABLE $ARCHIVE_DB_NAME.${ARCHIVE_TABLE_NAME}_Archive_Temp DISCARD TABLESPACE;"
    mysql --user="$ARCHIVE_DB_USER" --password="$ARCHIVE_DB_PASS" --host="$ARCHIVE_DB_HOST" --port=$ARCHIVE_DB_PORT -e "$MYSQL_QUERY"



    log_info "Import the tablespace to the temporary table: $ARCHIVE_TABLE_NAME"
    ARCHIVE_TEMP_PARTITION_FILE_NAME="${TABLE_NAME}_Archive_Temp.ibd"
    ARCHIVE_TEMP_PARTITION_FILE_PATH="$ARCHIVE_MACHINE_TEMP_FOLDER${ARCHIVE_TEMP_PARTITION_FILE_NAME}"

    ARCHIVE_TEMP_PARTITION_CFG_FILE_NAME="${TABLE_NAME}_Archive_Temp.cfg"
    ARCHIVE_TEMP_PARTITION_CFG_FILE_PATH="$ARCHIVE_MACHINE_TEMP_FOLDER${ARCHIVE_TEMP_PARTITION_CFG_FILE_NAME}"
    
    sshpass -p "$ARCHIVE_MACHINE_PASS" ssh -o StrictHostKeyChecking=no $ARCHIVE_MACHINE_USER@$ARCHIVE_MACHINE_HOST "echo '$ARCHIVE_MACHINE_PASS' | sudo -S docker cp $ARCHIVE_TEMP_PARTITION_FILE_PATH $ARCHIVE_CONTAINER_NAME:$ARCHIVE_CONTAINER_DATA_PATH"
    sshpass -p "$ARCHIVE_MACHINE_PASS" ssh -o StrictHostKeyChecking=no $ARCHIVE_MACHINE_USER@$ARCHIVE_MACHINE_HOST "echo '$ARCHIVE_MACHINE_PASS' | sudo -S docker cp $ARCHIVE_TEMP_PARTITION_CFG_FILE_PATH $ARCHIVE_CONTAINER_NAME:$ARCHIVE_CONTAINER_DATA_PATH"
    ARCHIVE_PARTITION_FILE_PATH="${ARCHIVE_CONTAINER_DATA_PATH}${ARCHIVE_TEMP_PARTITION_FILE_NAME}"
    ARCHIVE_PARTITION_CFG_FILE_PATH="${ARCHIVE_CONTAINER_DATA_PATH}${ARCHIVE_TEMP_PARTITION_CFG_FILE_NAME}"
    sshpass -p "$ARCHIVE_MACHINE_PASS" ssh -o StrictHostKeyChecking=no $ARCHIVE_MACHINE_USER@$ARCHIVE_MACHINE_HOST "echo '$ARCHIVE_MACHINE_PASS' | sudo -S docker exec  $ARCHIVE_CONTAINER_NAME chmod 660  $ARCHIVE_PARTITION_FILE_PATH"
    sshpass -p "$ARCHIVE_MACHINE_PASS" ssh -o StrictHostKeyChecking=no $ARCHIVE_MACHINE_USER@$ARCHIVE_MACHINE_HOST "echo '$ARCHIVE_MACHINE_PASS' | sudo -S docker exec  $ARCHIVE_CONTAINER_NAME chown mysql.mysql $ARCHIVE_PARTITION_FILE_PATH"
    sshpass -p "$ARCHIVE_MACHINE_PASS" ssh -o StrictHostKeyChecking=no $ARCHIVE_MACHINE_USER@$ARCHIVE_MACHINE_HOST "echo '$ARCHIVE_MACHINE_PASS' | sudo -S docker exec  $ARCHIVE_CONTAINER_NAME chmod 660  $ARCHIVE_PARTITION_CFG_FILE_PATH"
    sshpass -p "$ARCHIVE_MACHINE_PASS" ssh -o StrictHostKeyChecking=no $ARCHIVE_MACHINE_USER@$ARCHIVE_MACHINE_HOST "echo '$ARCHIVE_MACHINE_PASS' | sudo -S docker exec  $ARCHIVE_CONTAINER_NAME chown mysql.mysql $ARCHIVE_PARTITION_CFG_FILE_PATH"

    MYSQL_QUERY="ALTER TABLE $ARCHIVE_DB_NAME.${ARCHIVE_TABLE_NAME}_Archive_Temp IMPORT TABLESPACE;"
    mysql --user="$ARCHIVE_DB_USER" --password="$ARCHIVE_DB_PASS" --host="$ARCHIVE_DB_HOST" --port=$ARCHIVE_DB_PORT -e "$MYSQL_QUERY"

    log_info "Swap the tablespace with the destination table’s partition tablespace $ARCHIVE_TABLE_NAME"

    MYSQL_QUERY="ALTER TABLE $ARCHIVE_DB_NAME.$ARCHIVE_TABLE_NAME REORGANIZE PARTITION $ARCHIVE_NEW_PARTITION_MAXVALUE INTO (PARTITION $ARCHIVE_NEW_PARTITION_NAME VALUES LESS THAN ($ARCHIVE_NEW_PARTITION_DESCRIPTION), PARTITION $ARCHIVE_NEW_PARTITION_MAXVALUE VALUES LESS THAN (MAXVALUE));"
    mysql --user="$ARCHIVE_DB_USER" --password="$ARCHIVE_DB_PASS" --host="$ARCHIVE_DB_HOST"  --port=$ARCHIVE_DB_PORT -e "$MYSQL_QUERY"

    MYSQL_QUERY="ALTER TABLE $ARCHIVE_DB_NAME.$ARCHIVE_TABLE_NAME EXCHANGE PARTITION $ARCHIVE_NEW_PARTITION_NAME WITH TABLE $DB_NAME.${ARCHIVE_TABLE_NAME}_Archive_Temp;"
    mysql --user="$ARCHIVE_DB_USER" --password="$ARCHIVE_DB_PASS" --host="$ARCHIVE_DB_HOST"  --port=$ARCHIVE_DB_PORT -e "$MYSQL_QUERY"

    log_info "Drop table temp"
    MYSQL_QUERY="DROP TABLE $ARCHIVE_DB_NAME.${ARCHIVE_TABLE_NAME}_Archive_Temp;"
    mysql --user="$ARCHIVE_DB_USER" --password="$ARCHIVE_DB_PASS" --host="$ARCHIVE_DB_HOST"  --port=$ARCHIVE_DB_PORT -e "$MYSQL_QUERY"

}

function drop_partition_table(){
    DB_NAME=$1
    TABLE_NAME=$2
    PARTITION_NAME=$3
 
    DB_HOST_NAME=$4
    DB_HOST_PORT=$5
    DB_HOST_USER=$6
    DB_HOST_PASS=$7

    MYSQL_QUERY="ALTER TABLE $DB_NAME.$TABLE_NAME DROP PARTITION $PARTITION_NAME;"
    mysql --user="$DB_HOST_USER" --password="$DB_HOST_PASS" --host="$DB_HOST_NAME"  --port=$DB_HOST_PORT -e "$MYSQL_QUERY"
}

function reorganize_partition_table_afterweek(){
    DB_NAME=$1
    TABLE_NAME=$2
    AFTER_WEEKS=$3
    PARTITION_MAXVALUE_NAME=$4

    DB_HOST_NAME=$5
    DB_HOST_PORT=$6
    DB_HOST_USER=$7
    DB_HOST_PASS=$8
    
    MYSQL_QUERY="SELECT YEARWEEK(DATE_ADD(CURRENT_TIMESTAMP(), INTERVAL $AFTER_WEEKS WEEK));"
    PARTITION_NAME_VALUE=`mysql --user=$DB_HOST_USER   --port=$DB_HOST_PORT  --password=$DB_HOST_PASS --host=$DB_HOST_NAME -s -N -e "$MYSQL_QUERY"`

    MYSQL_QUERY="SELECT CONCAT('pw', YEARWEEK(DATE_ADD(CURRENT_TIMESTAMP(), INTERVAL $AFTER_WEEKS WEEK)) - 1);"
    PARTITION_NAME_REORGANIZE=`mysql --user=$DB_HOST_USER   --port=$DB_HOST_PORT  --password=$DB_HOST_PASS --host=$DB_HOST_NAME -s -N -e "$MYSQL_QUERY"`


    MYSQL_QUERY="SELECT PARTITION_NAME FROM  INFORMATION_SCHEMA.PARTITIONS WHERE TABLE_SCHEMA = '$DB_NAME' AND TABLE_NAME = '$TABLE_NAME' AND PARTITION_NAME = '$PARTITION_NAME_REORGANIZE';"
    VAR_TEMP=`mysql --user=$DB_HOST_USER   --port=$DB_HOST_PORT  --password=$DB_HOST_PASS --host=$DB_HOST_NAME -s -N -e "$MYSQL_QUERY"`
    if [ ! -z "$VAR_TEMP" ]
    then
      log_info "reorganize_partition_table_afterweek >> PARTION  $PARTION_NAME is exist"
      return
    fi

    MYSQL_QUERY="ALTER TABLE $DB_NAME.$TABLE_NAME REORGANIZE PARTITION $PARTITION_MAXVALUE_NAME INTO (PARTITION $PARTITION_NAME_REORGANIZE VALUES LESS THAN ($PARTITION_NAME_VALUE), PARTITION $PARTITION_MAXVALUE_NAME VALUES LESS THAN (MAXVALUE));"
    mysql --user=$DB_HOST_USER   --port=$DB_HOST_PORT  --password=$DB_HOST_PASS --host=$DB_HOST_NAME -e "$MYSQL_QUERY"
}

function get_old_partition_info_by_beforeweek(){
    DB_NAME=$1
    TABLE_NAME=$2
    BEFORE_WEEKS=$3
    COLUMN=$4

    DB_HOST_NAME=$5
    DB_HOST_PORT=$6
    DB_HOST_USER=$7
    DB_HOST_PASS=$8
    
    MYSQL_QUERY="SELECT $COLUMN FROM  INFORMATION_SCHEMA.PARTITIONS WHERE TABLE_SCHEMA= '$DB_NAME' AND TABLE_NAME = '$TABLE_NAME' AND PARTITION_NAME = CONCAT('pw', YEARWEEK(DATE_SUB(CURRENT_TIMESTAMP(), INTERVAL $BEFORE_WEEKS  WEEK))) LIMIT 1;"
    VALUE=`mysql --user=$DB_HOST_USER   --port=$DB_HOST_PORT  --password=$DB_HOST_PASS --host=$DB_HOST_NAME -s -N -e "$MYSQL_QUERY"`
    echo "$VALUE"
}

function check_partition_table_empty(){
    DB_NAME=$1
    TABLE_NAME=$2
    PARTITION_NAME=$3
    COLUMN=$4
 
    DB_HOST_NAME=$5
    DB_HOST_PORT=$6
    DB_HOST_USER=$7
    DB_HOST_PASS=$8
   
    MYSQL_QUERY="SELECT $COLUMN FROM $DB_NAME.$TABLE_NAME PARTITION ($PARTITION_NAME);"
    VALUE=`mysql --user=$DB_HOST_USER   --port=$DB_HOST_PORT  --password=$DB_HOST_PASS --host=$DB_HOST_NAME -s -N -e "$MYSQL_QUERY"`
    echo "$VALUE"
}

function  archive_delete_partition(){
    DB_NAME=$1
    TABLE_NAME=$2

    ARCHIVE_DB_NAME=$3
    ARCHIVE_TABLE_NAME=$4


    MASTER_DB_HOST=$5
    MASTER_DB_PORT=$6
    MASTER_DB_USER=$7
    MASTER_DB_PASS=$8


    SLAVE_DB_HOST=$9
    SLAVE_DB_PORT=${10}
    SLAVE_DB_USER=${11}
    SLAVE_DB_PASS=${12}
    SLAVE_CONTAINER_NAME=${13}
    SLAVE_CONTAINER_DATA_PATH=${14}
    SLAVE_MACHINE_TEMP_FOLDER=${15}


    ARCHIVE_DB_HOST=${16}
    ARCHIVE_DB_PORT=${17}
    ARCHIVE_DB_USER=${18}
    ARCHIVE_DB_PASS=${19}

    ARCHIVE_CONTAINER_NAME=${20}
    ARCHIVE_CONTAINER_DATA_PATH=${21}
  
    ARCHIVE_MACHINE_HOST=${22}
    ARCHIVE_MACHINE_USER=${23}
    ARCHIVE_MACHINE_PASS=${24}
    ARCHIVE_MACHINE_TEMP_FOLDER=${25}
    
    AFTER_WEEKS=${26}
    BEFORE_WEEKS=${27}
    

    PARTITION_NAME=$(get_old_partition_info_by_beforeweek $DB_NAME $TABLE_NAME $BEFORE_WEEKS "PARTITION_NAME" $SLAVE_DB_HOST $SLAVE_DB_PORT $SLAVE_DB_USER $SLAVE_DB_PASS)
    if [ -z "$PARTITION_NAME" ]
    then
      log_info "PARTITION_NAME not found with BEFORE_WEEKS=$BEFORE_WEEKS"
      return
    fi

    VAR_TEMP_1=$(check_partition_table_empty $DB_NAME $TABLE_NAME $PARTITION_NAME "TransID" $MASTER_DB_HOST $MASTER_DB_PORT $MASTER_DB_USER $MASTER_DB_PASS)
    if [ -z "$VAR_TEMP_1" ]
    then
      log_info "PARTITION $PARTITION_NAME on master is empty"
      drop_partition_table $DB_NAME $TABLE_NAME $PARTITION_NAME  $MASTER_DB_HOST $MASTER_DB_PORT $MASTER_DB_USER $MASTER_DB_PASS
      return
    fi

    ARCHIVE_NEW_PARTITION_NAME=$PARTITION_NAME
    ARCHIVE_NEW_PARTITION_DESCRIPTION=$(get_old_partition_info_by_beforeweek $DB_NAME $TABLE_NAME $BEFORE_WEEKS "PARTITION_DESCRIPTION" $SLAVE_DB_HOST $SLAVE_DB_PORT $SLAVE_DB_USER $SLAVE_DB_PASS)
    ARCHIVE_NEW_PARTITION_MAXVALUE=$PARTITION_MAXVALUE_NAME

    SLAVE_PARTITION_FILE_NAME="${TABLE_NAME}#P#${PARTITION_NAME}.ibd"
    SLAVE_PARTITION_CFG_FILE_NAME="${TABLE_NAME}#P#${PARTITION_NAME}.cfg"

    copy_archive_partition  $DB_NAME $TABLE_NAME  $SLAVE_DB_HOST $SLAVE_DB_PORT $MASTER_DB_USER $MASTER_DB_PASS $SLAVE_PARTITION_FILE_NAME  $SLAVE_PARTITION_CFG_FILE_NAME $SLAVE_MACHINE_TEMP_FOLDER $SLAVE_CONTAINER_NAME $SLAVE_CONTAINER_DATA_PATH $ARCHIVE_MACHINE_HOST $ARCHIVE_MACHINE_USER $ARCHIVE_MACHINE_PASS $ARCHIVE_MACHINE_TEMP_FOLDER

    import_partition_table $ARCHIVE_DB_NAME $ARCHIVE_TABLE_NAME $ARCHIVE_DB_HOST $ARCHIVE_DB_PORT $ARCHIVE_DB_USER $ARCHIVE_DB_PASS $ARCHIVE_MACHINE_HOST $ARCHIVE_MACHINE_USER $ARCHIVE_MACHINE_PASS $ARCHIVE_MACHINE_TEMP_FOLDER $ARCHIVE_CONTAINER_NAME $ARCHIVE_CONTAINER_DATA_PATH $ARCHIVE_NEW_PARTITION_NAME $ARCHIVE_NEW_PARTITION_DESCRIPTION $ARCHIVE_NEW_PARTITION_MAXVALUE
    
    VAR_TEMP_2=$(check_partition_table_empty $ARCHIVE_DB_NAME $ARCHIVE_TABLE_NAME $PARTITION_NAME "TransID" $ARCHIVE_DB_HOST $ARCHIVE_DB_PORT $ARCHIVE_DB_USER $ARCHIVE_DB_PASS)
    if [ -z "$VAR_TEMP_2" ]
    then
      log_info "PARTITION $PARTITION_NAME on archive is empty"
      return
    fi
    
    reorganize_partition_table_afterweek  $DB_NAME $TABLE_NAME $AFTER_WEEKS  $PARTITION_MAXVALUE_NAME $MASTER_DB_HOST $MASTER_DB_PORT $MASTER_DB_USER $MASTER_DB_PASS

    drop_partition_table $DB_NAME $TABLE_NAME $PARTITION_NAME  $MASTER_DB_HOST $MASTER_DB_PORT $MASTER_DB_USER $MASTER_DB_PASS

}








#log functions

log_trace(){
  if [[ $LOG_LEVEL -le 1 ]]
  then
    do_log TRACE $1
  fi
}

log_debug(){
  if [[ $LOG_LEVEL -le 2 ]]
  then
    do_log DEBUG $1
  fi
}

log_info(){
  if [[ $LOG_LEVEL -le 3 ]]
  then
    do_log INFO $1
  fi
}

log_warning(){
  if [[ $LOG_LEVEL -le 4 ]]
  then
    do_log WARN $1
  fi
}

log_error(){
  if [[ $LOG_LEVEL -le 5 ]]
  then
    do_log ERROR $1
  fi
}

log_fatal(){
  if [[ $LOG_LEVEL -le 6 ]]
  then
    do_log FATAL $1
  fi
}

